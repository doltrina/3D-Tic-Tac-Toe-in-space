#!/bin/bash
# ========================================================
#   Запуск локального сервера Космических Крестиков-Ноликов
#   (macOS / Linux)
# ========================================================

cd "$(dirname "$0")"

echo "========================================================"
echo "  Запуск сервера Космических Крестиков-Ноликов 3D (LAN) "
echo "========================================================"
echo ""

# Проверка наличия Node.js
if ! command -v node &> /dev/null; then
    echo "[ОШИБКА] Node.js не найден в вашей системе!"
    echo "Пожалуйста, установите Node.js:"
    echo "  - macOS: brew install node (или скачайте с https://nodejs.org/)"
    echo "  - Linux: sudo apt install nodejs npm (или через менеджер пакетов)"
    echo ""
    exit 1
fi

# Проверка и установка зависимостей при первом запуске
if [ ! -d "node_modules" ]; then
    echo "[ИНФО] Папка node_modules не найдена. Установка зависимостей..."
    npm install
    if [ $? -ne 0 ]; then
        echo "[ОШИБКА] Не удалось выполнить npm install!"
        exit 1
    fi
    echo "[УСПЕХ] Зависимости установлены."
    echo ""
fi

# Запуск сервера
node server.js
